/* ============================ 自检 ============================ */

function plainText(xml) {
  return (xml.match(/<w:t[^>]*>([\s\S]*?)<\/w:t>/g) || [])
    .map(s => s.replace(/<[^>]+>/g, ''))
    .join('\n')
    .replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&amp;/g, '&');
}

const problems = [];
function fail(msg) { problems.push(msg); }

function audit(t, xml) {
  const text = plainText(xml);
  // 1. 占位符白名单
  const used = [...new Set((text.match(/\{\{([^{}]+)\}\}/g) || []).map(s => s.slice(2, -2)))];
  const bad = used.filter(k => !PLACEHOLDERS.includes(k));
  if (bad.length) fail(t.id + ' 出现白名单外占位符：' + bad.join('、'));
  // 2. 无孤立括号
  const br = (text.match(/\{\{/g) || []).length, ere = (text.match(/\}\}/g) || []).length;
  if (br !== ere) fail(t.id + ' 占位符括号不成对（' + br + ' 对 ' + ere + '）');
  const bare = text.replace(/\{\{[^{}]+\}\}/g, '');
  if (bare.includes('{{') || bare.includes('}}')) fail(t.id + ' 存在孤立的花括号');
  // 3. 不得含下划线格式元素
  if (/<w:u[\s/>]/.test(xml)) fail(t.id + ' 含 <w:u> 下划线格式元素');
  // 4. {{CAUSE}} 后须为「纠纷」
  const m = [...text.matchAll(/\{\{CAUSE\}\}(.{0,3})/g)];
  for (const x of m) if (!x[1].startsWith('纠纷') && !x[1].startsWith('}')) fail(t.id + ' 出现未接「纠纷」的 {{CAUSE}}：…' + x[1]);
  // 5. 不得用 UPFRONT_FEE 表达保全数额
  if (/\{\{UPFRONT_FEE/.test(text)) fail(t.id + ' 使用了 {{UPFRONT_FEE}}，该占位符专用于律师费');
  // 6. 段落数下限
  const pc = (xml.match(/<w:p>/g) || []).length;
  if (pc < 6) fail(t.id + ' 段落数不足（' + pc + '）');
  // 7. 标题非空
  if (!text.includes(t.name)) fail(t.id + ' 正文缺少标题');
  return { used, pc };
}

