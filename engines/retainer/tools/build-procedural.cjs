const esc = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
/* 中文用指定字体，西文与数字统一 Times New Roman（律所公文版式规范） */
const rpr = (font, sz, bold) => '<w:rPr><w:rFonts w:hint="eastAsia" w:ascii="Times New Roman" w:hAnsi="Times New Roman" w:eastAsia="' + font + '" w:cs="Times New Roman"/>' + (bold ? '<w:b/><w:bCs/>' : '') + '<w:sz w:val="' + sz + '"/><w:szCs w:val="' + sz + '"/></w:rPr>';

function run(text, font, sz, bold) {
  return '<w:r>' + rpr(font, sz, bold) + '<w:t xml:space="preserve">' + esc(text) + '</w:t></w:r>';
}

function para(text, o) {
  o = o || {};
  const font = o.font || '仿宋', sz = o.sz || 24, bold = !!o.bold, jc = o.jc || 'both';
  const ind = o.indent === false ? '' : '<w:ind w:firstLineChars="200" w:firstLine="480"/>';
  const sp = o.space || '<w:spacing w:line="360" w:lineRule="auto"/>';
  return '<w:p><w:pPr>' + sp + ind + '<w:jc w:val="' + jc + '"/>' + rpr(font, sz, bold) + '</w:pPr>' + run(text, font, sz, bold) + '</w:p>';
}

/* 多行文本按换行拆为多个段落，共用同一排版参数 */
function paras(text, o) {
  return String(text).split('\n').map(line => para(line, o)).join('');
}

