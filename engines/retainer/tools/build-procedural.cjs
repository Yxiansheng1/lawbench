/* ============================ 主流程 ============================ */

(async () => {
  // 越界防护：输出目录必须位于 procedural-templates 之内
  if (!OUTDIR.startsWith(path.join(ROOT, 'procedural-templates'))) {
    console.error('输出目录越界，中止：' + OUTDIR);
    process.exit(1);
  }

  const results = [];
  let scannedPlaceholders = new Set();

  for (const t of T) {
    const xml = buildXml(t);
    const info = audit(t, xml);
    info.used.forEach(k => scannedPlaceholders.add(k));
    results.push({ id: t.id, dir: t.dir, name: t.name, file: t.id + ' ' + t.name + '.docx', xml, paraCount: info.pc, used: info.used });
  }

  if (problems.length) {
    console.error('自检未通过，未写入任何文件：');
    problems.forEach(p => console.error('  ' + p));
    process.exit(1);
  }

  const out = { generated: 0, files: [] };
  if (!CHECK) {
    fs.mkdirSync(OUTDIR, { recursive: true });
    for (const r of results) {
      const dir = path.join(OUTDIR, r.dir);
      fs.mkdirSync(dir, { recursive: true });
      const target = path.join(dir, r.file);
      if (!target.startsWith(OUTDIR)) { console.error('写入路径越界，中止：' + target); process.exit(1); }
      const t = T.find(x => x.id === r.id);
      fs.writeFileSync(target, await buildDocx(t));
    }
    fs.writeFileSync(path.join(OUTDIR, 'README.md'), buildReadme(), 'utf8');
    fs.writeFileSync(path.join(OUTDIR, '通用母版.md'), buildMaster(), 'utf8');
    out.generated = results.length;
  }

  console.log(JSON.stringify({
    mode: CHECK ? 'check' : 'write',
    outdir: OUTDIR,
    templates: results.length,
    placeholdersUsed: [...scannedPlaceholders].sort(),
    byDir: results.reduce((a, r) => (a[r.dir] = (a[r.dir] || 0) + 1, a), {}),
    files: results.map(r => r.dir + '/' + r.file)
  }, null, 1));
})().catch(e => { console.error(e); process.exit(1); });
